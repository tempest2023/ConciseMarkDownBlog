'use strict';

// About and Work share their facts with the personal agent. Edit profile.json.
const fs = require('fs');
const path = require('path');
const profile = require('../src/data/profile.json');
const root = path.resolve(__dirname, '../src/articles');
const link = page => `/?page=${encodeURIComponent(page)}`;
const engineering = profile.highlights.filter(item => item.kind === 'engineering');
const ongoing = profile.highlights.filter(item => item.kind === 'ongoing-research');
const organizations = profile.highlights.filter(item => item.kind === 'organization');
const research = profile.highlights.filter(item => item.kind === 'research');
const writingTitles = {
  'Blogs/AI/My_AI_Research_and_Engineering_Journey': 'From Deep Learning to Production AI Agents',
  'Blogs/DeepLearning/Civilization_Intelligence': 'Civilizational Intelligence'
};
const compact = item => `### [${item.name}](/?page=Work#${item.id})\n\n*${item.label}*\n\n${item.summary}`;
const detail = item => {
  const paragraphs = item.paragraphs || [item.problem, item.contribution, item.approach];
  const label = item.linkLabel ?? (item.kind === 'research' ? 'Read the paper' : 'Read the project background');
  const url = item.paragraphs || item.kind === 'research' ? item.url : link(item.source);
  return `<section id="${item.id}">\n\n### ${item.name}\n\n*${item.label}*\n\n${paragraphs.join('\n\n')}${label && url ? `\n\n[${label}](${url})` : ''}\n\n</section>`;
};
const about = `<!-- Generated by scripts/generate-profile.js from src/data/profile.json -->
<div class="profile-hero">
<p class="eyebrow">${profile.name} · ${profile.role}</p>

# ${profile.headline}

${profile.intro}

<nav class="profile-actions" aria-label="Explore my work"><a href="/?page=Work">Work & research ↗</a><a href="${profile.contact.resume}">My résumé ↗</a></nav>
</div>

## Six years in China and the US

${profile.journey.join('\n\n')}

## What I'm working on

${profile.current.summary} [Nova at Newfront](/?page=Work#nova-agent)

At Rein, I help maintain the community's learning resources and develop Nori, the assistant we use to delegate work and collect the results. [Rein Protocol Foundation](/?page=Work#rein-foundation) · [Nori](/?page=Projects/Project#nori)

My current research looks at permission decisions. If an agent asks to read a file, can a model tell whether the user's original request authorizes that read? [Agent permissions and safety](/?page=Work#agent-safety)

## Selected research

${research.map(compact).join('\n\n')}

## Writing

${profile.featuredWriting.map(page => `- [${writingTitles[page]}](${link(page)})`).join('\n')}

[Browse all writing](/?page=Blog)

## Let's connect

${profile.contact.invitation}

[Email me](mailto:${profile.contact.email}) or find me on [GitHub](${profile.contact.github}) and [LinkedIn](${profile.contact.linkedin}).
`;
const work = `<!-- Generated by scripts/generate-profile.js from src/data/profile.json -->
# Work & Research

November 2026

## Agent engineering

${engineering.map(detail).join('\n\n')}

## Organization building

${organizations.map(detail).join('\n\n')}

## Research in progress

${ongoing.map(detail).join('\n\n')}

## Selected research

${research.map(detail).join('\n\n')}

## Earlier research

${profile.research.map(item => `### [${item.name}](${item.url})\n\n${item.summary}`).join('\n\n')}

## Experience

${profile.experience.map(item => `### ${item.organization}\n\n*${item.period}*\n\n${item.summary}`).join('\n\n')}

## Education

${profile.education.map(item => `- **${item.institution}** — ${item.degree}, ${item.period}`).join('\n')}

[Complete résumé](${profile.contact.resume}) · [Selected projects](/?page=Projects/Project) · [Contact ${profile.name}](mailto:${profile.contact.email})
`;
fs.writeFileSync(path.join(root, 'About.md'), about);
fs.writeFileSync(path.join(root, 'Work.md'), work);
console.log('Generated About and Work from the public profile.');
